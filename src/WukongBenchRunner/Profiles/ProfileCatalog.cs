namespace WukongBenchRunner.Profiles;

/// <summary>
/// Профили двух проходов. Пары «разрешение ↔ индекс в меню» и высоты рендера взяты
/// из конфигов, которые бенчмарк сохраняет сам через меню: произвольные значения
/// могут уронить его на старте, поэтому используются только «родные» комбинации.
/// </summary>
public static class ProfileCatalog
{
    public static BenchmarkProfile Cpu { get; } = new(
        TestKind.Cpu,
        "CPU-тест",
        new GraphicsSettings(
            Width: 1280,
            Height: 720,
            ResolutionIndex: 2,
            RenderScalePercent: 50,
            RenderHeight: 356,
            Quality: QualityPreset.Low),
        [
            "Минимальное разрешение и 50% масштаб рендеринга: видеокарта рисует ~640×360, " +
                "время кадра на GPU становится маленьким и упирается всё в CPU.",
            "Все параметры качества на минимуме: меньше нагрузки на шейдеры, тени и постобработку (это работа GPU).",
            "Трассировка лучей и генерация кадров выключены: RT грузит GPU, а генерация кадров " +
                "дорисовывает кадры без участия CPU и искажает результат.",
            "VSync и ограничение FPS выключены: иначе FPS упрётся в частоту монитора, а не в процессор.",
            "Работа CPU при этом почти не уменьшается: игровая логика, анимация, физика и подготовка " +
                "draw calls не зависят от разрешения, поэтому FPS показывает именно скорость процессора.",
        ]);

    public static BenchmarkProfile Gpu { get; } = new(
        TestKind.Gpu,
        "GPU-тест",
        new GraphicsSettings(
            Width: 1920,
            Height: 1080,
            ResolutionIndex: 0,
            RenderScalePercent: 100,
            RenderHeight: 1080,
            Quality: QualityPreset.Cinematic),
        [
            "Все параметры качества на максимуме (Кинематографическое): самые тяжёлые тени, " +
                "глобальное освещение, отражения и растительность.",
            "Масштаб рендеринга 100%: апскейлер не снижает внутреннее разрешение, каждый пиксель считается честно.",
            "Генерация кадров выключена: она поднимает FPS за счёт вставленных кадров и скрывает реальную " +
                "производительность GPU.",
            "VSync и ограничение FPS выключены: видеокарта работает без простоев, загрузка ~100%.",
            "Трассировка лучей выключена намеренно: она доступна не на всех видеокартах, а неподдерживаемое " +
                "значение в конфиге роняет бенчмарк. Так результаты сравнимы между любыми GPU.",
        ]);

    public static IReadOnlyList<BenchmarkProfile> All { get; } = [Cpu, Gpu];
}
